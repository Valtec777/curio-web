2. OBJETIVO DESTA POLÍTICA
Esta Política explica, em linguagem clara, quais dados pessoais podem ser tratados no CURIÓ, por que são utilizados, com quem podem ser compartilhados, por quanto tempo podem ser mantidos e como os titulares ou seus responsáveis podem exercer seus direitos.

3. QUAIS DADOS PODEMOS TRATAR
Conforme a relação com o CURIÓ, podem ser tratados:
• dados cadastrais e de contato, como nome, nome preferido, e-mail, telefone e relação do responsável com o estudante;
• dados do estudante, como nome, ano escolar, escola, matérias acompanhadas e preferências de uso;
• dados pedagógicos, como missões atribuídas, respostas, atividades, arquivos enviados, avaliações, devolutivas, progresso, habilidades observadas e histórico de acompanhamento;
• dados de agenda e comunicação, como encontros, links de reunião, mensagens e registros de atendimento;
• dados contratuais e financeiros, como plano, competência de pagamento, comprovantes e status de conferência;
• dados de segurança e acesso, como identificadores de conta, registros de autenticação, eventos de acesso, PIN da área da família e informações técnicas necessárias à proteção da conta;
• arquivos enviados voluntariamente, como PDFs, imagens de atividades, materiais escolares e comprovantes;
• preferências, como avatar, notificações, acessibilidade e interesses em novos cursos.

O CURIÓ deve evitar a coleta de informações excessivas. Dados pessoais sensíveis ou informações de saúde somente devem ser tratados quando realmente necessários, com finalidade definida e salvaguardas adequadas.

4. PARA QUE USAMOS OS DADOS
Os dados podem ser tratados para:
• criar e administrar contas e vínculos entre estudante, família e professor;
• prestar o acompanhamento educacional contratado;
• organizar missões, atividades, materiais, avaliações, agenda e relatórios;
• permitir comunicação entre os perfis autorizados;
• registrar pagamentos e conferir comprovantes;
• gerar contratos, documentos e evidências operacionais;
• personalizar a experiência pedagógica sem utilizar critérios discriminatórios;
• oferecer recursos de segurança, suporte, prevenção a fraude e auditoria;
• cumprir obrigações legais e regulatórias;
• desenvolver, medir e melhorar o serviço de forma compatível com os direitos dos titulares.

5. BASES LEGAIS
O tratamento poderá se apoiar, conforme o caso, nas bases legais previstas na Lei Geral de Proteção de Dados Pessoais — LGPD, incluindo execução de contrato ou procedimentos preliminares, cumprimento de obrigação legal ou regulatória, exercício regular de direitos, legítimo interesse quando aplicável e compatível com os direitos do titular, e consentimento quando exigido ou escolhido como base adequada.

Para crianças e adolescentes, qualquer operação deverá priorizar o melhor interesse do estudante. Quando a legislação exigir consentimento específico e destacado de pai, mãe ou responsável legal, esse consentimento será solicitado de forma separada e compreensível.

6. CRIANÇAS E ADOLESCENTES
O CURIÓ é um serviço de acesso provável por crianças e adolescentes e, por isso, adota proteção reforçada. A plataforma deve:
• limitar dados ao necessário para a finalidade educacional e de segurança;
• oferecer informações compreensíveis para famílias e estudantes;
• permitir supervisão familiar compatível com idade e desenvolvimento;
• evitar publicidade comportamental direcionada com base em perfil infantil;
• não condicionar atividades ao fornecimento de dados desnecessários;
• proteger imagem, voz, identidade, produções escolares e histórico pedagógico;
• manter controles de acesso por perfil e vínculo.

Há um aviso específico de “Privacidade da Criança” com linguagem voltada ao contexto infantojuvenil.

7. COMPARTILHAMENTO E OPERADORES
O CURIÓ pode utilizar prestadores de infraestrutura, autenticação, armazenamento, hospedagem, comunicação, videoconferência, pagamento e ferramentas técnicas estritamente necessárias ao serviço. Esses terceiros devem receber somente os dados necessários à sua função e estarão sujeitos a obrigações de segurança e confidencialidade conforme o contrato e a legislação aplicável.

Não vendemos dados pessoais a anunciantes.

Quando serviços de tecnologia envolverem tratamento ou armazenamento fora do Brasil, deverão ser observadas as regras aplicáveis de transferência internacional de dados e salvaguardas adequadas.

8. INTELIGÊNCIA ARTIFICIAL
Recursos de IA, quando ativados, devem ser usados como apoio à elaboração e organização de conteúdo, nunca como substituição automática da avaliação pedagógica humana quando houver impacto relevante sobre o estudante. Arquivos e dados pessoais não devem ser enviados a um provedor de IA sem necessidade, base legal, configuração de privacidade e avaliação de segurança compatíveis.

9. RETENÇÃO E EXCLUSÃO
Os dados serão mantidos pelo tempo necessário às finalidades informadas, à execução contratual, ao atendimento de obrigações legais, à defesa em processos e à preservação de histórico pedagógico ou financeiro quando legitimamente necessário.

A lixeira operacional do sistema pode manter itens recuperáveis por prazo técnico antes da eliminação ou anonimização, sem afastar prazos legais de guarda aplicáveis.

10. SEGURANÇA
São adotadas medidas técnicas e administrativas proporcionais ao risco, como controle de acesso por função e vínculo, autenticação, políticas de banco de dados, armazenamento privado, links temporários para arquivos, logs de auditoria, separação de dados mais sensíveis e revisão de permissões.

Nenhum sistema é absolutamente imune a incidentes. Caso ocorra incidente com risco ou dano relevante, serão adotadas as medidas de contenção, investigação e comunicação previstas na legislação e nas orientações da autoridade competente.

11. DIREITOS DOS TITULARES
Nos limites da LGPD, o titular ou seu representante pode solicitar confirmação de tratamento, acesso, correção, informação sobre compartilhamentos, portabilidade quando aplicável, revisão de decisões automatizadas quando cabível, eliminação ou anonimização nas hipóteses legais, revogação de consentimento e demais direitos previstos em lei.

